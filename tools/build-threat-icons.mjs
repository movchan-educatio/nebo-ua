// Builds assets/threats/sprite.svg from the individual SVG files.
//
// The six standalone SVGs are the single source of truth. The sprite is a
// generated artefact so the DOM (<use>) and the canvas radar can never drift
// from the artwork. tests/threat-sprite.test.js regenerates and compares, so a
// hand-edit of the sprite fails CI.
//
// Symbol ids intentionally match radar/filters.js KIND_SYMBOL so no consumer
// has to change: shahed/uav -> drone artwork, missile, ballistic, kab,
// aircraft, other.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const threatsDir = path.join(here, '..', 'assets', 'threats');
const OUT = path.join(threatsDir, 'sprite.svg');

// id -> source file. `shahed` is an alias of the drone artwork.
const MAP = [
  ['shahed', 'drone.svg'],
  ['uav', 'drone.svg'],
  ['fpv', 'drone.svg'],
  ['recon', 'drone.svg'],
  ['missile', 'cruise-missile.svg'],
  ['ballistic', 'ballistic.svg'],
  ['kab', 'kab.svg'],
  ['aircraft', 'aviation.svg'],
  ['other', 'other-threat.svg'],
];

export function buildSprite() {
  const cache = new Map();
  const read = (f) => {
    if (!cache.has(f)) cache.set(f, fs.readFileSync(path.join(threatsDir, f), 'utf8'));
    return cache.get(f);
  };
  const symbols = MAP.map(([id, file]) => {
    const raw = read(file);
    const vb = raw.match(/viewBox="([^"]+)"/)?.[1];
    if (!vb) throw new Error(`${file}: no viewBox`);
    // Body = everything inside the root <svg>, minus the root tag itself.
    const body = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    // The standalone files carry role/aria-label for standalone use; inside a
    // symbol they would be duplicated a11y text, so they are dropped here.
    const clean = body.replace(/\s*(role|aria-label)="[^"]*"/g, '');
    return `  <symbol id="${id}" viewBox="${vb}">${clean}</symbol>`;
  }).join('\n');
  return `<!-- GENERATED by tools/build-threat-icons.mjs — do not edit by hand.
     Source of truth: assets/threats/*.svg -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols}
</svg>
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const out = buildSprite();
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${MAP.length} symbols, ${out.length} bytes)`);
}